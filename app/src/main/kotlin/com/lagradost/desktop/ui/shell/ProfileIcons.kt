data class ProfileIcon(val id: String, val name: String, val category: String)

object ProfileIconLoader {
    private val cache = ConcurrentHashMap<String, ImageBitmap>()

    fun load(id: String): ImageBitmap? {
        val cached = cache[id]
        if (cached != null) return cached
        return runCatching {
            val stream = ProfileIconLoader::class.java.classLoader.getResourceAsStream("profile_icons/$id.webp")
                ?: return@runCatching null
            val bytes = stream.use { it.readBytes() }
            val bmp = Image.makeFromEncoded(bytes).toComposeImageBitmap()
            cache[id] = bmp
            bmp
        }.getOrNull()
    }
}

